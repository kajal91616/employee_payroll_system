--------------------------------------------------------
-- 2. CREATE DATABASE TABLES
--------------------------------------------------------
CREATE TABLE departments (
    dept_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dept_name VARCHAR2(100) NOT NULL UNIQUE
);

CREATE TABLE employees (
    emp_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name   VARCHAR2(50) NOT NULL,
    last_name    VARCHAR2(50) NOT NULL,
    dept_id      NUMBER REFERENCES departments(dept_id),
    basic_salary NUMBER(10, 2) NOT NULL,
    hire_date    DATE DEFAULT SYSDATE
);

CREATE TABLE payroll (
    payroll_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emp_id         NUMBER REFERENCES employees(emp_id),
    pay_month      VARCHAR2(7) NOT NULL, -- Format: YYYY-MM
    basic_pay      NUMBER(10, 2) NOT NULL,
    allowances     NUMBER(10, 2) NOT NULL,
    tax_deduction  NUMBER(10, 2) NOT NULL,
    net_salary     NUMBER(10, 2) NOT NULL,
    generated_date DATE DEFAULT SYSDATE,
    CONSTRAINT uk_emp_month UNIQUE (emp_id, pay_month)
);

