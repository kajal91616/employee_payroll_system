-- 4. PACKAGE SPECIFICATION: payroll_pkg
--------------------------------------------------------
CREATE OR REPLACE PACKAGE payroll_pkg AS
    PROCEDURE generate_payroll(
        p_emp_id    IN NUMBER,
        p_pay_month IN VARCHAR2,
        p_message   OUT VARCHAR2
    );
END payroll_pkg;
/

--------------------------------------------------------
-- 5. PACKAGE BODY: payroll_pkg
--------------------------------------------------------
CREATE OR REPLACE PACKAGE BODY payroll_pkg AS

    -- Private Function to calculate allowances (20% of basic salary)
    FUNCTION calc_allowances(p_basic IN NUMBER) RETURN NUMBER IS
    BEGIN
        RETURN p_basic * 0.20;
    END calc_allowances;

    -- Private Function to calculate tax deduction based on gross salary slabs
    FUNCTION calc_tax(p_gross IN NUMBER) RETURN NUMBER IS
    BEGIN
        IF p_gross > 80000 THEN
            RETURN p_gross * 0.15;
        ELSIF p_gross > 50000 THEN
            RETURN p_gross * 0.10;
        ELSE
            RETURN p_gross * 0.05;
        END IF;
    END calc_tax;

    -- Public Procedure to generate/merge payroll securely
    PROCEDURE generate_payroll(
        p_emp_id    IN NUMBER,
        p_pay_month IN VARCHAR2,
        p_message   OUT VARCHAR2
    ) IS
        v_basic     NUMBER(10, 2);
        v_allowance NUMBER(10, 2);
        v_gross     NUMBER(10, 2);
        v_tax       NUMBER(10, 2);
        v_net       NUMBER(10, 2);
    BEGIN
        -- Fetch basic salary for the selected employee
        SELECT basic_salary 
        INTO v_basic 
        FROM employees 
        WHERE emp_id = p_emp_id;

        -- Perform salary calculations
        v_allowance := calc_allowances(v_basic);
        v_gross     := v_basic + v_allowance;
        v_tax       := calc_tax(v_gross);
        v_net       := v_gross - v_tax;

        -- Use MERGE to prevent duplicate entries for the same month
        MERGE INTO payroll p
        USING (SELECT p_emp_id AS emp_id, p_pay_month AS pay_month FROM dual) src
        ON (p.emp_id = src.emp_id AND p.pay_month = src.pay_month)
        WHEN MATCHED THEN
            UPDATE SET 
                basic_pay      = v_basic,
                allowances     = v_allowance,
                tax_deduction  = v_tax,
                net_salary     = v_net,
                generated_date = SYSDATE
        WHEN NOT MATCHED THEN
            INSERT (emp_id, pay_month, basic_pay, allowances, tax_deduction, net_salary, generated_date)
            VALUES (p_emp_id, p_pay_month, v_basic, v_allowance, v_tax, v_net, SYSDATE);

        COMMIT;
        v_message := 'Success: Payslip generated for Employee ID ' || p_emp_id || ' (' || p_pay_month || ')';

    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            v_message := 'Error: Employee ID ' || p_emp_id || ' does not exist.';
        WHEN OTHERS THEN
            v_message := 'Unexpected Error: ' || SQLERRM;
    END generate_payroll;

END payroll_pkg;
/